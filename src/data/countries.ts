/** Generate emoji flag from ISO 3166-1 alpha-2 code */
export function toFlagEmoji(iso2: string): string {
  return [...iso2.toUpperCase()]
    .map(c => String.fromCodePoint(0x1f1e6 + c.charCodeAt(0) - 65))
    .join("")
}

