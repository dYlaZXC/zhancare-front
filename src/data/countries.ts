const featuredIso2 = new Set(FEATURED.map(c => c.iso2))
const rest = ALL
  .filter(c => !featuredIso2.has(c.iso2))
  .sort((a, b) => a.nameRu.localeCompare(b.nameRu, "ru"))

export const featuredCountries: Country[] = FEATURED
export const allCountries: Country[] = rest
export const everyCountry: Country[] = [...FEATURED, ...rest]

export function findCountryByIso2(iso2: string): Country | undefined {
  return everyCountry.find(c => c.iso2 === iso2)
}
